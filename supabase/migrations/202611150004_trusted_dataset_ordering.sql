alter table public.dataset_versions
  add column if not exists version_sequence bigint
    generated by default as identity;

with ordered_versions as (
  select
    id,
    row_number() over (
      order by example_count, created_at, id
    )::bigint as sequence_number
  from public.dataset_versions
)
update public.dataset_versions as versions
set version_sequence = ordered_versions.sequence_number
from ordered_versions
where versions.id = ordered_versions.id;

select setval(
  pg_get_serial_sequence(
    'public.dataset_versions',
    'version_sequence'
  )::regclass,
  coalesce(max(version_sequence), 1),
  max(version_sequence) is not null
)
from public.dataset_versions;

create unique index if not exists dataset_versions_sequence_unique
  on public.dataset_versions (version_sequence);

create unique index if not exists dataset_versions_single_active
  on public.dataset_versions (release_status)
  where release_status = 'active';

create or replace function public.activate_trusted_dataset(
  target_version_id uuid,
  target_actor_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_evaluation_status text;
begin
  perform pg_advisory_xact_lock(834761002);

  select evaluation_status into target_evaluation_status
    from public.dataset_versions
    where id = target_version_id
    for update;
  if not found or target_evaluation_status <> 'passed' then
    raise exception 'dataset has not passed evaluation';
  end if;

  update public.dataset_versions
    set release_status = 'rolled_back'
    where release_status = 'active'
      and id <> target_version_id;

  update public.dataset_versions
    set release_status = 'active',
        approved_by = target_actor_id,
        approved_at = now()
    where id = target_version_id
      and evaluation_status = 'passed';
  if not found then
    raise exception 'dataset release failed';
  end if;

  insert into public.intelligence_audit_logs (
    actor_id, action, dataset_version_id, metadata
  )
  values (
    target_actor_id,
    'trusted_dataset_activated',
    target_version_id,
    jsonb_build_object('evaluation_status', 'passed')
  );
end;
$$;
